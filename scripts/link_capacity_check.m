function R = link_capacity_check(cfg,duplex,resDir,figDir)
%LINK_CAPACITY_CHECK Per-link practical QPSK capacity and TDM frame sizing.
% Rs=BW/(1+rolloff); C=Rs*bits/symbol*code-rate*(1-TDD-overhead).
raw=cfg.recommendedBandwidth_Hz/(1+cfg.rolloff)*cfg.modulationBitsPerSymbol*cfg.codingRate/1e6;
radioNet=raw*(1-duplex.OverheadFraction);
demands=[cfg.trunkRateTarget_Mbps cfg.siteRateTarget_Mbps];
slotNet=cfg.tdmSlotPayload_bits*cfg.tdmFrameRate_Hz/1e6*(1-duplex.OverheadFraction);
slots=ceil(demands./(slotNet*cfg.linkLoadWarningFraction));
grossBits=slots*cfg.tdmSlotPayload_bits+cfg.tdmFrameOverheadBits_perLink;
grossRate=grossBits*cfg.tdmFrameRate_Hz/1e6;payloadRate=slots*slotNet;
util=demands./payloadRate;rawUtil=demands/radioNet;
links=cfg.linkNames(:);capacity=repmat(radioNet,4,1);demand=demands(:);tdmSlots=slots(:);
T=table(links,demand,capacity,repmat(cfg.modulationBitsPerSymbol,4,1), ...
 repmat(cfg.codingRate,4,1),repmat(duplex.OverheadFraction*100,4,1), ...
 tdmSlots,repmat(cfg.tdmSlotPayload_bits,4,1),repmat(cfg.tdmFrameRate_Hz,4,1), ...
 grossBits(:),grossRate(:),payloadRate(:),rawUtil(:)*100,util(:)*100, ...
 floor(radioNet/cfg.voiceChannelRate_kbps*1000)*ones(4,1), ...
 floor(radioNet/cfg.e1LikeRate_Mbps)*ones(4,1),floor(radioNet/cfg.videoStreamRate_Mbps)*ones(4,1), ...
 util(:)>cfg.linkLoadWarningFraction, ...
 'VariableNames',{'Link','Demand_Mbps','RadioNetCapacity_Mbps','BitsPerSymbol','CodeRate', ...
 'TDDOverhead_percent','TdmSlots','PayloadBitsPerSlot','FrameRate_Hz','GrossFrameBits', ...
 'GrossTdmRate_Mbps','NetTdmPayloadCapacity_Mbps','RadioUtilization_percent', ...
 'TdmUtilization_percent','VoiceChannels_64kbps','E1LikeStreams_2Mbps', ...
 'VideoStreams_4Mbps','Above80PercentLoad'});
writetable(T,fullfile(resDir,'Link_Capacity_Check.csv'));
f=figure('Visible','off','Color','w');tiledlayout(1,2,'Padding','compact');
nexttile;bar(util*100,'FaceColor',[0 .42 .72]);hold on;yline(cfg.linkLoadWarningFraction*100,'r--','80% threshold');
xticklabels({'A-B','B-C','B-D','B-E'});ylabel('Allocated TDM utilization (%)');title('TDM loading per link');grid on;
nexttile;bar([demand(:) payloadRate(:) capacity(:)]);xticklabels({'A-B','B-C','B-D','B-E'});
ylabel('Rate (Mbps)');title('Demand, TDM payload and radio capacity');legend('Demand','TDM payload','Radio capacity','Location','best');grid on;
ax=findall(f,'Type','axes');set(ax,'Color','w','XColor','k','YColor','k');saveas(f,fullfile(figDir,'Figure_26_Link_Capacity_Utilisation.png'));close(f);
R=struct('Table',T,'RadioNetCapacity_Mbps',radioNet,'PerLinkDemand_Mbps',demands(:), ...
 'PerLinkUtilization',rawUtil(:),'TdmUtilization',util(:),'SlotNetRate_Mbps',slotNet, ...
 'TotalRadioCapacity_Mbps',radioNet);
end
