function R = final_design_summary(cfg,linkFull,feeder,capacity,propagation,resDir,figDir)
%FINAL_DESIGN_SUMMARY Assemble per-link design and assumed equipment-cost tables.
% EIRP=Pt+Gt-Ltx; Pr=EIRP+Gr-Lrx-Lother-FSPL; cost=sum(quantity*assumed unit cost).
n=numel(cfg.extendedLinkDistance_km);
linkNames=linkFull.Link;
txType=cfg.linkTxAntenna(:);rxType=cfg.linkRxAntenna(:);
txGain=linkFull.TxAntennaGain_dBi;rxGain=linkFull.RxAntennaGain_dBi;
feederLength=cfg.feederLengths_m(:);
feederLoss=feeder.PerLink.TotalFeederLoss_dB;
mismatch=feeder.PerLink.MismatchLoss_dB;
radioCapacity=repmat(capacity.RadioNetCapacity_Mbps,n,1);
demand=[capacity.PerLinkDemand_Mbps(:);zeros(n-numel(capacity.PerLinkDemand_Mbps),1)];
utilization=100*demand/radioCapacity(1);
modulation=repmat({cfg.modulationName},n,1);
coding=repmat({sprintf('FEC rate %.2f',cfg.codingRate)},n,1);
duplex=repmat({'TDD'},n,1);
availability=propagation.RayleighAvailability;
R=table(linkNames,linkFull.Frequency_GHz,linkFull.ITU_Band,linkFull.Distance_km, ...
 linkFull.EIRP_dBm,txType,txGain,rxType,rxGain,feederLength,feederLoss,mismatch, ...
 linkFull.FSPL_dB,linkFull.ReceivedPower_dBm,linkFull.NoiseFloor_dBm,linkFull.SNR_dB, ...
 linkFull.FadeMargin_dB,linkFull.ResidualFadeMargin_dB,availability,radioCapacity,demand, ...
 utilization,modulation,coding,duplex, ...
 'VariableNames',{'Link','Frequency_GHz','ITU_Band','Distance_km','EIRP_dBm', ...
 'TxAntennaType','TxGain_dBi','RxAntennaType','RxGain_dBi','FeederLength_m', ...
 'FeederLossPerEnd_dB','MismatchLoss_dB','FSPL_dB','ReceivedPower_dBm','NoiseFloor_dBm', ...
 'SNR_dB','FadeMargin_dB','ResidualFadeMargin_dB','Availability','RadioCapacity_Mbps', ...
 'Demand_Mbps','RadioUtilization_percent','Modulation','Coding','DuplexMethod'});
writetable(R,fullfile(resDir,'Final_Design_Summary.csv'));

% Costed redundant topology: seven links, two radios and two feeder runs per link.
categories={'Radios';'Dish antennas';'Panel antennas';'Yagi antennas';'Feeder cable'; ...
 'Connectors';'Masts';'Power and backup';'Lightning protection'};
quantity=[cfg.radioUnitsPerLink*cfg.redundantTopologyLinkCount;cfg.redundantTopologyAntennaCounts(:); ...
 cfg.redundantTopologyLinkCount*cfg.feederRunsPerLink*cfg.feederLength_m; ...
 cfg.connectorCountPerLink*cfg.redundantTopologyLinkCount;cfg.siteCount*cfg.mastPerSite; ...
 cfg.siteCount*cfg.powerSystemPerSite;cfg.siteCount*cfg.lightningKitPerSite];
unit={'radio';'antenna';'antenna';'antenna';'m';'connector';'mast';'site system';'kit'};
unitCost=[cfg.radioCost_USD;cfg.dishCost_USD;cfg.panelCost_USD;cfg.yagiCost_USD; ...
 cfg.feederCost_USD_per_m;cfg.connectorCost_USD;cfg.mastCost_USD; ...
 cfg.powerBackupCost_USD;cfg.lightningProtectionCost_USD];
cost=quantity.*unitCost;
E=table(categories,quantity,unit,unitCost,cost, ...
 'VariableNames',{'EquipmentCategory','Quantity','Unit','AssumedUnitCost_USD','ExtendedCost_USD'});
E=[E;table({'TOTAL';'Budget cap';'Budget remaining'},[NaN;NaN;NaN],{'USD';'USD';'USD'}, ...
 [NaN;cfg.budgetCap_USD;NaN],[sum(cost);cfg.budgetCap_USD;cfg.budgetCap_USD-sum(cost)], ...
 'VariableNames',E.Properties.VariableNames)];
writetable(E,fullfile(resDir,'Equipment_List.csv'));

f=figure('Visible','off','Color','w','Position',[100 100 1680 1010]);
tiledlayout(2,1,'Padding','compact','TileSpacing','compact');
ax1=nexttile;axis(ax1,[0 1 0 1]);axis(ax1,'off');
text(ax1,.02,.94,'Final design per-link summary','FontSize',13,'FontWeight','bold','Color','k');
text(ax1,.02,.78,sprintf('%-5s %6s %8s %8s %8s %7s %10s %9s %8s', ...
 'Link','km','EIRP dBm','FSPL dB','Rx dBm','SNR dB','Residual dB','Avail.','Cap/Dem'), ...
 'FontName','FixedWidth','FontSize',8,'Color','k');
for k=1:height(R)
 text(ax1,.02,.67-(k-1)*.09,sprintf('%-5s %6.1f %8.2f %8.2f %8.2f %7.2f %10.2f %9.4f %4.1f/%-4.1f', ...
  R.Link{k},R.Distance_km(k),R.EIRP_dBm(k),R.FSPL_dB(k),R.ReceivedPower_dBm(k), ...
  R.SNR_dB(k),R.ResidualFadeMargin_dB(k),R.Availability(k),R.RadioCapacity_Mbps(k),R.Demand_Mbps(k)), ...
  'FontName','FixedWidth','FontSize',8,'Color','k');
end
nexttile;bar(cost,'FaceColor',[.1 .5 .72]);xticks(1:numel(categories));xticklabels(categories);
xtickangle(20);ylabel('Illustrative equipment cost (USD)');title(sprintf('Redundant topology: total $%.0f of $%.0f budget',sum(cost),cfg.budgetCap_USD));grid on;
ax=findall(f,'Type','axes');set(ax,'Color','w','XColor','k','YColor','k');
saveas(f,fullfile(figDir,'Figure_34_Final_Design_Summary.png'));close(f);
perLink=R;R=struct('PerLink',perLink,'Equipment',E,'EquipmentCost_USD',sum(cost), ...
 'BudgetCap_USD',cfg.budgetCap_USD);
end
